"""Build the display-only WOFF2 shards using the explicitly prepared local venv."""
import json
import sys
from pathlib import Path
from io import BytesIO

import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

UPSTREAM = 'https://github.com/google/fonts/tree/477b6577b3a9a9e3229eb8e0946da806d2cf822b/ofl/notoseriftc'
ASSET_LIMIT = 1_200_000

def ranges(points):
    spans=[]
    for cp in sorted(points):
        if spans and cp == spans[-1][1]+1:
            spans[-1][1]=cp
        else:
            spans.append([cp,cp])
    return ','.join('U+%X'%a if a==b else 'U+%X-%X'%(a,b) for a,b in spans)

source,license_path,characters=map(Path,sys.argv[1:4])
text=json.loads(characters.read_text(encoding='utf8'))
original_license=license_path.read_text(encoding='utf8')
if 'SIL OPEN FONT LICENSE Version 1.1' not in original_license:
    raise ValueError('Unexpected font license')
source_font=TTFont(source)
version=source_font['name'].getDebugName(5)
font=instantiateVariableFont(source_font,{'wght':(600,600,700)},inplace=True)
for name in font['name'].names:
    s=name.toUnicode()
    revised=s.replace('Noto Serif TC','Conduit Display TC').replace('NotoSerifTC','ConduitDisplayTC')
    if s!=revised:
        name.string=revised.encode(name.getEncoding(),errors='replace')
origin=BytesIO()
font.save(origin)
assets,css,missing={},[],set()
for part,chars in text.items():
    font=TTFont(BytesIO(origin.getvalue()))
    opts=subset.Options()
    opts.hinting=False
    subsetter=subset.Subsetter(options=opts)
    subsetter.populate(text=chars)
    subsetter.subset(font)
    font.flavor='woff2'
    out=BytesIO()
    font.save(out)
    name=f'conduit-{part}.woff2'
    assets[name]=out.getvalue()
    actual=set(font.getBestCmap())
    expected=set(map(ord,chars))
    assert actual<=expected
    missing|=expected-actual
    css.append(f'@font-face{{font-family:"Conduit Display TC";src:url("/fonts/{name}") format("woff2");font-style:normal;font-weight:600 700;font-display:swap;unicode-range:{ranges(actual)}}}')
    print(f'{name}: {len(assets[name])} bytes, {len(actual)} codepoints')
if sum(map(len,assets.values()))>ASSET_LIMIT:
    raise ValueError('Heading fonts exceed the 1.2 MB budget')
if missing:
    print('Not in source font; will fall back:', ' '.join(f'U+{cp:04X}' for cp in sorted(missing)))
target=Path('public/fonts')
target.mkdir(parents=True,exist_ok=True)
for name,data in assets.items():
    (target/name).write_bytes(data)
notice=f'Conduit Display TC — a subset of Noto Serif TC ({version})\nSource: {UPSTREAM}\nBuild tools: Python {sys.version.split()[0]}, fontTools {fontTools.__version__}, Brotli {brotli.__version__}\n\n'
(target/'LICENSE-OFL.txt').write_text(notice+original_license,encoding='utf8',newline='\n')
Path('src/styles/display-fonts.css').write_text('/* Generated by tools/subset-font.py. */\n'+'\n'.join(css)+'\n',encoding='utf8',newline='\n')
